// Command vsop87 writes sky/vsop87.go, the VSOP87D series for the Earth and
// the five classical planets, from the files published by the CDS (catalogue
// VI/81; Bretagnon & Francou, Astron. Astrophys. 202, 309, 1988). It's run by
// hand when the cutoff changes, not as part of the build; its output is
// committed.
//
//	mkdir vsop87 && cd vsop87
//	for e in mer ven ear mar jup sat; do curl -LO https://cdsarc.cds.unistra.fr/ftp/VI/81/VSOP87D.$e; done
//	cd .. && go run ./internal/tools/vsop87 vsop87 sky/vsop87.go
//
// The full series are far more precise than the sky needs, so terms too small
// to matter between 1800 and 2200 are dropped: a term of the series in T^k,
// with amplitude A, is kept if A × 0.2^k is at least the cutoff (T is in
// Julian millennia from J2000, so |T| ≤ 0.2 in those years). It reports the
// largest error that leaves in each planet's heliocentric longitude, latitude
// and distance, sampled across the range.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// planets are the bodies kept, by file extension, with the names used in
// the generated code.
var planets = []struct{ ext, name string }{
	{"mer", "mercury"}, {"ven", "venus"}, {"ear", "earth"}, {"mar", "mars"}, {"jup", "jupiter"}, {"sat", "saturn"},
}

// term is A cos(B + C T).
type term struct{ a, b, c float64 }

// series is one planet's: by variable (L, B, R), by power of T.
type series [3][][]term

func main() {
	cutoff := flag.Float64("cutoff", 1e-7, "smallest A × 0.2^k kept")
	flag.Parse()
	if flag.NArg() != 2 {
		fmt.Fprintln(os.Stderr, "usage: vsop87 [-cutoff A] DIR OUTPUT.go")
		os.Exit(2)
	}
	if err := run(flag.Arg(0), flag.Arg(1), *cutoff); err != nil {
		fmt.Fprintln(os.Stderr, "vsop87:", err)
		os.Exit(1)
	}
}

func run(dir, out string, cutoff float64) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/vsop87 from the VSOP87D files of CDS catalogue VI/81; DO NOT EDIT.\n\n")
	b.WriteString("package sky\n\n")
	total, kept := 0, 0
	for _, p := range planets {
		full, err := parse(filepath.Join(dir, "VSOP87D."+p.ext))
		if err != nil {
			return err
		}
		cut := truncate(full, cutoff)
		n, k := count(full), count(cut)
		total, kept = total+n, kept+k
		maxErr := compare(full, cut)
		fmt.Fprintf(os.Stderr, "%-8s %5d of %5d terms; largest error L %.3f″ B %.3f″ R %.2e au\n",
			p.name, k, n, maxErr[0]*rad2arcsec, maxErr[1]*rad2arcsec, maxErr[2])
		write(&b, p.name, cut)
	}
	fmt.Fprintf(os.Stderr, "kept %d of %d terms\n", kept, total)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

const rad2arcsec = 180 / math.Pi * 3600

// parse reads a VSOP87D file. Each block starts with a header line naming the
// variable (1–3) and the power of T; each term line ends with A, B and C.
func parse(path string) (series, error) {
	var s series
	f, err := os.Open(path)
	if err != nil {
		return s, err
	}
	defer func() { _ = f.Close() }()
	v, k := -1, -1
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.Contains(line, "VSOP87 VERSION D") {
			i := strings.Index(line, "VARIABLE ")
			j := strings.Index(line, "*T**")
			if i < 0 || j < 0 {
				return s, fmt.Errorf("%s: bad header %q", path, line)
			}
			v = int(line[i+len("VARIABLE ")] - '1')
			k = int(line[j+len("*T**")] - '0')
			if v < 0 || v > 2 || k < 0 || k > 5 {
				return s, fmt.Errorf("%s: bad header %q", path, line)
			}
			for len(s[v]) <= k {
				s[v] = append(s[v], nil)
			}
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 3 || v < 0 {
			continue
		}
		var t term
		for i, dst := range []*float64{&t.a, &t.b, &t.c} {
			if *dst, err = strconv.ParseFloat(fields[len(fields)-3+i], 64); err != nil {
				return s, fmt.Errorf("%s: %q: %w", path, line, err)
			}
		}
		s[v][k] = append(s[v][k], t)
	}
	return s, sc.Err()
}

func truncate(s series, cutoff float64) series {
	var out series
	for v := range s {
		out[v] = make([][]term, len(s[v]))
		for k, terms := range s[v] {
			scale := math.Pow(0.2, float64(k))
			for _, t := range terms {
				if t.a*scale >= cutoff {
					out[v][k] = append(out[v][k], t)
				}
			}
		}
	}
	return out
}

func count(s series) int {
	n := 0
	for v := range s {
		for _, terms := range s[v] {
			n += len(terms)
		}
	}
	return n
}

func eval(s series, v int, t float64) float64 {
	sum, tk := 0.0, 1.0
	for _, terms := range s[v] {
		x := 0.0
		for _, tm := range terms {
			x += tm.a * math.Cos(tm.b+tm.c*t)
		}
		sum += x * tk
		tk *= t
	}
	return sum
}

// compare returns the largest difference between the series in each
// variable, sampled every 10 days from 1800 to 2200.
func compare(full, cut series) [3]float64 {
	var maxErr [3]float64
	for days := -73050.0; days <= 73050; days += 10 {
		t := days / 365250
		for v := range 3 {
			maxErr[v] = math.Max(maxErr[v], math.Abs(eval(full, v, t)-eval(cut, v, t)))
		}
	}
	return maxErr
}

func write(b *bytes.Buffer, name string, s series) {
	fmt.Fprintf(b, "var %s = vsop87{\n", name)
	for v := range s {
		b.WriteString("\t{\n")
		for _, terms := range s[v] {
			b.WriteString("\t\t{\n")
			for _, t := range terms {
				fmt.Fprintf(b, "\t\t\t{%s, %s, %s},\n", num(t.a), num(t.b), num(t.c))
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
}

func num(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }
