// Command licenses writes internal/licenses/modules.go, the list of modules
// the build depends on with their versions, checksums and licences. It's run
// by go generate in internal/licenses whenever go.mod changes:
//
//	go generate ./internal/licenses
//
// It reads the requirements from go.mod and their checksums from go.sum, and
// identifies each module's licence from the licence file at the root of its
// copy in the module cache, downloading it first if need be.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: licenses MODULE-ROOT OUTPUT.go")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "licenses:", err)
		os.Exit(1)
	}
}

type module struct {
	Path, Version, Sum, License string
	Indirect                    bool
}

func run(root, out string) error {
	mods, err := requirements(root)
	if err != nil {
		return err
	}
	sums, err := checksums(filepath.Join(root, "go.sum"))
	if err != nil {
		return err
	}
	dirs, err := download(root, mods)
	if err != nil {
		return err
	}
	for i := range mods {
		m := &mods[i]
		key := m.Path + " " + m.Version
		if m.Sum = sums[key]; m.Sum == "" {
			return fmt.Errorf("no go.sum entry for %s", key)
		}
		if m.License, err = license(dirs[key]); err != nil {
			return fmt.Errorf("%s: %w", key, err)
		}
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/licenses from go.mod and go.sum; DO NOT EDIT.\n\n")
	b.WriteString("package licenses\n\nvar modules = []Module{\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "\t{Path: %q, Version: %q, Sum: %q, License: %q, Indirect: %t},\n",
			m.Path, m.Version, m.Sum, m.License, m.Indirect)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// requirements returns the modules go.mod requires.
func requirements(root string) ([]module, error) {
	cmd := exec.Command("go", "mod", "edit", "-json")
	cmd.Dir = root
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go mod edit: %w", err)
	}
	var gomod struct {
		Require []module
		Replace []struct{ Old module }
	}
	if err := json.Unmarshal(data, &gomod); err != nil {
		return nil, err
	}
	if len(gomod.Replace) > 0 {
		return nil, errors.New("go.mod has replace directives, which aren't supported")
	}
	return gomod.Require, nil
}

// checksums returns the module checksums in go.sum, keyed by "path version".
func checksums(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	sums := map[string]string{}
	s := bufio.NewScanner(f)
	for s.Scan() {
		fields := strings.Fields(s.Text())
		if len(fields) != 3 || strings.HasSuffix(fields[1], "/go.mod") {
			continue
		}
		sums[fields[0]+" "+fields[1]] = fields[2]
	}
	return sums, s.Err()
}

// download fetches mods into the module cache, if they aren't already, and
// returns their directories there, keyed by "path version".
func download(root string, mods []module) (map[string]string, error) {
	args := []string{"mod", "download", "-json"}
	for _, m := range mods {
		args = append(args, m.Path+"@"+m.Version)
	}
	cmd := exec.Command("go", args...)
	cmd.Dir = root
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go mod download: %w", err)
	}
	dirs := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(data))
	for {
		var m struct{ Path, Version, Dir, Error string }
		if err := dec.Decode(&m); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, err
		}
		if m.Error != "" {
			return nil, fmt.Errorf("go mod download %s@%s: %s", m.Path, m.Version, m.Error)
		}
		dirs[m.Path+" "+m.Version] = m.Dir
	}
	return dirs, nil
}

// licenseFile matches the names of licence files, most likely first.
var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying)(\.(md|txt))?$`)

// license identifies the licence of the module in dir from the licence file
// at its root.
func license(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	for _, e := range entries {
		if e.Type().IsRegular() && licenseFile.MatchString(e.Name()) {
			text, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				return "", err
			}
			return identify(string(text)), nil
		}
	}
	return "Unknown", nil
}

// spdxTag matches a licence file's own SPDX identifier.
var spdxTag = regexp.MustCompile(`SPDX-License-Identifier:\s*(.+)`)

// identify names the licence in text with its SPDX identifier: the file's
// own, if it gives one, and otherwise by recognizing the licences common
// among Go modules by phrases from their text.
func identify(text string) string {
	if m := spdxTag.FindStringSubmatch(text); m != nil {
		return strings.TrimSpace(m[1])
	}
	t := strings.Join(strings.Fields(strings.ToLower(text)), " ")
	has := func(phrases ...string) bool {
		for _, p := range phrases {
			if !strings.Contains(t, p) {
				return false
			}
		}
		return true
	}
	switch {
	case has("your choice of", "the freetype license", "gnu general public license (gpl), version 2 or later"):
		return "FTL OR GPL-2.0-or-later"
	case has("apache license", "version 2.0"):
		return "Apache-2.0"
	case has("mozilla public license", "version 2.0"):
		return "MPL-2.0"
	case has("gnu lesser general public license", "version 3"):
		return "LGPL-3.0"
	case has("gnu lesser general public license", "version 2.1"):
		return "LGPL-2.1"
	case has("gnu general public license", "version 3"):
		return "GPL-3.0"
	case has("gnu general public license", "version 2"):
		return "GPL-2.0"
	case has("do what the fuck you want to public license"):
		return "WTFPL"
	case has("this is free and unencumbered software released into the public domain"):
		return "Unlicense"
	case has("permission is hereby granted, free of charge"):
		return "MIT"
	case has("permission to use, copy, modify, and/or distribute this software for any purpose"),
		has("permission to use, copy, modify, and distribute this software for any purpose"):
		return "ISC"
	case has("redistribution and use in source and binary forms", "neither the name"),
		has("redistribution and use in source and binary forms", "names of its contributors may"):
		return "BSD-3-Clause"
	case has("redistribution and use in source and binary forms"):
		return "BSD-2-Clause"
	}
	return "Unknown"
}
